UNIPROT_STREAM = "https://rest.uniprot.org/uniprotkb/stream"
UNIPROT_QUERY = "(reviewed:true) AND (organism_id:9606)"
UNIPROT_TERMS = "https://www.uniprot.org/help/license"
DEEPLOC_TRAIN_URL = (
    "https://services.healthtech.dtu.dk/services/DeepLoc-2.0/data/"
    "Swissprot_Train_Validation_dataset.csv"
)
DEEPLOC_CITATION = (
    "Thumuluri et al., DeepLoc 2.0: multi-label subcellular localization prediction "
    "using protein language models. Nucleic Acids Research (2022). "
    "https://doi.org/10.1093/nar/gkac278"
)
DEEPLOC_LOCATION_COLUMNS = [
    "Cell membrane",
    "Cytoplasm",
    "Endoplasmic reticulum",
    "Extracellular",
    "Golgi apparatus",
    "Lysosome/Vacuole",
    "Mitochondrion",
    "Nucleus",
    "Peroxisome",
    "Plastid",
]
DEFAULT_TIMEOUT = 90
MAX_UNIPROT_LIMIT = 10000
MAX_DEEPLOC_LIMIT = 30000


def generate_toy_classification_records() -> list[dict]:
    """Deterministic synthetic protein-like sequences with localization-style labels.

    This fixture is for tests and pipeline smoke runs. It is not a scientific benchmark.
    Homolog groups differ by one residue so k-mer Jaccard stays high within a group.
    """
    families = [
        ("nucleus", "MKWVTFISLLFLFSSAYSRGVFRRHHHKKK", "nucleus_fam"),
        ("nucleus", "QPLARNWYSTCMNDEAAAWWWYYYTTTNNN", "nucleus_fam2"),
        ("cytoplasm", "GAVLIPFYWSTCMNQDEKRHDDEEFFQQQQ", "cyto_fam"),
        ("cytoplasm", "NNNNCCCCEEEEPPPPYYYYTTTTSSSSAA", "cyto_fam2"),
        ("membrane", "IIIIVVVVLGAVLISTAAAWWWMMMGGGTT", "mem_fam"),
        ("membrane", "LLLLFFFAAACDEFGHIKLMNPQRSTVVVV", "mem_fam2"),
    ]
    records = []
    alphabet = "ACDEFGHIKLMNPQRSTVWY"
    for label, core, family in families:
        for i in range(3):
            seq = core[:-1] + alphabet[i]
            rid = f"{family}_{i + 1}"
            records.append({
                "id": rid,
                "sequence": seq,
                "label": label,
                "family": family,
                "description": f"synthetic {label} member of {family}",
            })
    singletons = [
        ("nucleus", "WWYYPPPGGGAAAQQQNNNNCCCC", "nucleus_unique"),
        ("cytoplasm", "RRRTTTSSSMMMKKKEEEVVVQQQ", "cyto_unique"),
        ("membrane", "FFFFLLLLIIIIYYYYHHHHWWWW", "mem_unique"),
    ]
    for label, seq, family in singletons:
        records.append({
            "id": family,
            "sequence": seq,
            "label": label,
            "family": family,
            "description": f"synthetic singleton {label}",
        })
    return records


def write_toy_classification_csv(path: str | Path) -> tuple[Path, Path]:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    records = generate_toy_classification_records()
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["id", "sequence", "label", "family", "description"],
        )
        writer.writeheader()
        writer.writerows(records)
    manifest = write_manifest(
        _manifest_path(path),
        {
            "source": "toy_classification",
            "license": "MIT (synthetic fixture generated by BioAudit; not biological data)",
            "citation": None,
            "record_count": len(records),
            "path": str(path),
            "sha256": sha256_file(path),
            "preprocessing": [
                "Generated deterministically by bioaudit.dataset.generate_toy_classification_records",
                "Labels are synthetic (nucleus/cytoplasm/membrane) and have no UniProt origin",
            ],
            "retrieved_at_utc": utc_now_iso(),
        },
    )
    return path, manifest


def download_uniprot_fasta(
    limit: int,
    out: str | Path,
    timeout: int = DEFAULT_TIMEOUT,
    opener=urlopen,
    retries: int = 1,
) -> tuple[Path, Path]:
    if not 1 <= limit <= MAX_UNIPROT_LIMIT:
        raise ValueError(f"UniProt --limit must be between 1 and {MAX_UNIPROT_LIMIT}")
    params = urlencode({
        "query": UNIPROT_QUERY,
        "format": "fasta",
        "size": limit,
    })
    url = f"{UNIPROT_STREAM}?{params}"
    request = Request(url, headers={"User-Agent": "BioAudit/0.1 (educational project)"})
    content = None
    last_error: Exception | None = None
    attempts = max(1, retries + 1)
    for _ in range(attempts):
        try:
            with opener(request, timeout=timeout) as response:
                content = response.read().decode("utf-8")
            last_error = None
            break
        except (HTTPError, URLError, TimeoutError, OSError) as exc:
            last_error = exc
    if last_error is not None or content is None:
        raise RuntimeError(f"UniProt download failed: {last_error}") from last_error
    if not content.strip().startswith(">"):
        raise RuntimeError(
            "UniProt returned no FASTA records. Check the query, API status, and that "
            "the response is FASTA rather than HTML or JSON."
        )
    out_path = Path(out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    records = read_fasta(out_path)
    if len(records) > limit:
        from Bio import SeqIO
        from Bio.Seq import Seq
        from Bio.SeqRecord import SeqRecord
        trimmed = records[:limit]
        SeqIO.write(
            [SeqRecord(Seq(r["sequence"]), id=r["id"], description=r.get("description", "")) for r in trimmed],
            out_path,
            "fasta",
        )
        records = trimmed
        preprocessing = [
            f"Truncated UniProt stream output to the first {limit} records",
        ]
    else:
        preprocessing = [f"Wrote {len(records)} FASTA records from UniProt stream"]
    manifest = write_manifest(
        _manifest_path(out_path),
        {
            "source": "UniProtKB/Swiss-Prot reviewed human proteins (organism_id:9606)",
            "source_url": url,
            "terms": UNIPROT_TERMS,
            "license_note": "UniProt content remains subject to UniProt terms; not redistributed by this repo by default.",
            "query": UNIPROT_QUERY,
            "requested_limit": limit,
            "record_count": len(records),
            "path": str(out_path),
            "sha256": sha256_file(out_path),
            "response_sha256": sha256_bytes(content.encode("utf-8")),
            "retrieved_at_utc": utc_now_iso(),
            "timeout_seconds": timeout,
            "preprocessing": preprocessing,
            "suitable_supervised_benchmark": False,
            "reason": (
                "Reviewed human proteins do not automatically provide a classification label "
                "suitable as the main supervised experiment."
            ),
        },
    )
    return out_path, manifest


def _manifest_path(data_path: Path) -> Path:
    return data_path.with_name(data_path.name + ".manifest.json")


def _curl_get(url: str, timeout: int) -> str:
    curl = shutil.which("curl") or shutil.which("curl.exe")
    if not curl:
        raise RuntimeError("curl is not available to retry the download after an SSL error")
    with tempfile.NamedTemporaryFile(delete=False, suffix=".csv") as handle:
        dest = Path(handle.name)
    try:
        proc = subprocess.run(
            [curl, "-fsSL", "--max-time", str(timeout), "-o", str(dest), url],
            capture_output=True,
            text=True,
            check=False,
        )
        if proc.returncode != 0:
            raise RuntimeError(proc.stderr.strip() or f"curl exited {proc.returncode}")
        return dest.read_text(encoding="utf-8")
    finally:
        dest.unlink(missing_ok=True)


def _http_get(url: str, timeout: int, opener, retries: int) -> str:
    request = Request(url, headers={"User-Agent": "BioAudit/0.1 (educational project)"})
    content = None
    last_error: Exception | None = None
    attempts = max(1, retries + 1)
    for _ in range(attempts):
        try:
            with opener(request, timeout=timeout) as response:
                raw = response.read()
            content = raw.decode("utf-8")
            last_error = None
            break
        except (HTTPError, URLError, TimeoutError, OSError, ssl.SSLError) as exc:
            last_error = exc
    if content is not None:
        return content
    ssl_failure = isinstance(last_error, ssl.SSLError) or "CERTIFICATE" in str(last_error)
    if ssl_failure and opener is urlopen:
        try:
            return _curl_get(url, timeout)
        except Exception as curl_exc:
            raise RuntimeError(
                f"Download failed for {url}: {last_error}; curl fallback: {curl_exc}"
            ) from last_error
    raise RuntimeError(f"Download failed for {url}: {last_error}") from last_error


def _is_positive(value: object) -> bool:
    if value is True:
        return True
    try:
        if pd.isna(value):
            return False
    except (TypeError, ValueError):
        pass
    text = str(value).strip().lower()
    return text in {"1", "1.0", "true", "yes"} or text == "1"


def parse_deeploc_single_label_rows(text: str, limit: int | None = None) -> list[dict]:
    """Keep proteins with exactly one of the ten DeepLoc location flags."""
    from io import StringIO

    df = pd.read_csv(StringIO(text))
    missing = [col for col in ["ACC", "Sequence", *DEEPLOC_LOCATION_COLUMNS] if col not in df.columns]
    if missing:
        raise ValueError(
            "DeepLoc CSV is missing expected columns "
            f"{missing}. Available: {list(df.columns)}"
        )
    records = []
    skipped_multi = 0
    skipped_none = 0
    for _, row in df.iterrows():
        positives = [col for col in DEEPLOC_LOCATION_COLUMNS if _is_positive(row[col])]
        if len(positives) == 0:
            skipped_none += 1
            continue
        if len(positives) > 1:
            skipped_multi += 1
            continue
        seq = "".join(str(row["Sequence"]).split()).upper()
        if len(seq) < 40:
            continue
        partition = row["Partition"] if "Partition" in df.columns else None
        records.append({
            "id": str(row["ACC"]),
            "sequence": seq,
            "label": positives[0],
            "partition": "" if pd.isna(partition) else str(int(partition) if float(partition).is_integer() else partition),
            "kingdom": "" if "Kingdom" not in df.columns or pd.isna(row["Kingdom"]) else str(row["Kingdom"]),
        })
        if limit is not None and len(records) >= limit:
            break
    if not records:
        raise RuntimeError(
            "No single-label DeepLoc records remained after filtering. "
            f"Skipped multi-label={skipped_multi}, no-label={skipped_none}."
        )
    return records


def download_deeploc_localization(
    out: str | Path,
    limit: int | None = 3000,
    timeout: int = 180,
    opener=urlopen,
    retries: int = 1,
    raw_out: str | Path | None = None,
) -> tuple[Path, Path]:
    """Download DeepLoc 2.0 train/validation CSV and write a single-label subset.

    Multi-label proteins are excluded so the current logistic baseline has one class
    per sequence. DeepLoc homology partitions are preserved in the ``partition`` column.
    """
    if limit is not None and not 1 <= limit <= MAX_DEEPLOC_LIMIT:
        raise ValueError(f"DeepLoc --limit must be between 1 and {MAX_DEEPLOC_LIMIT}")
    content = _http_get(DEEPLOC_TRAIN_URL, timeout, opener, retries)
    if "ACC" not in content.splitlines()[0]:
        raise RuntimeError(
            "DeepLoc download did not look like the expected CSV (missing ACC header). "
            "Check the URL and that the response is not an HTML error page."
        )
    raw_path = Path(raw_out or Path(out).with_name("deeploc_swissprot_train_validation.csv"))
    raw_path.parent.mkdir(parents=True, exist_ok=True)
    raw_path.write_text(content, encoding="utf-8")
    records = parse_deeploc_single_label_rows(content, limit=limit)
    out_path = Path(out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["id", "sequence", "label", "partition", "kingdom"])
        writer.writeheader()
        writer.writerows(records)
    label_counts: dict[str, int] = {}
    for rec in records:
        label_counts[rec["label"]] = label_counts.get(rec["label"], 0) + 1
    manifest = write_manifest(
        _manifest_path(out_path),
        {
            "source": "DeepLoc 2.0 Swiss-Prot train/validation set (DTU Health Tech)",
            "source_url": DEEPLOC_TRAIN_URL,
            "citation": DEEPLOC_CITATION,
            "terms_note": (
                "Data are derived from UniProt and redistributed by the DeepLoc authors. "
                "Cite DeepLoc 2.0 and UniProt. Do not treat this copy as our dataset."
            ),
            "requested_limit": limit,
            "record_count": len(records),
            "label_counts": label_counts,
            "path": str(out_path),
            "raw_path": str(raw_path),
            "raw_sha256": sha256_file(raw_path),
            "sha256": sha256_file(out_path),
            "retrieved_at_utc": utc_now_iso(),
            "timeout_seconds": timeout,
            "preprocessing": [
                "Downloaded official DeepLoc 2.0 training/validation CSV",
                "Kept proteins with exactly one of ten location labels",
                "Dropped sequences shorter than 40 residues",
                "Preserved DeepLoc homology Partition (0-4, max 30% sequence similarity)",
                f"Capped processed output at {limit} records" if limit else "No processed-record cap",
            ],
            "suitable_supervised_benchmark": True,
            "label_policy": "single-location only; multi-label proteins excluded",
        },
    )
    return out_path, manifest
